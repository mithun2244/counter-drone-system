const LANG = "en";

function t(key, values = {}) {
  const text = key.split(".").reduce((node, part) => node && node[part], TEXT[LANG]);
  if (typeof text !== "string") return key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}
